//! One-time import of the `model/` folder into the RBAC store: the first
//! start with RBAC on and an empty `model_files` table.

use std::collections::{BTreeSet, HashMap};
use std::path::{Path, PathBuf};

use cubemodel::{DataModel, ModelError, ModelLoader};
use uuid::Uuid;

use super::model_snapshot::validate_path;
use super::model_store::ModelChange;
use super::store::Store;

const SYNC_MARKER: &str = "# Generated by sync-sofiadb-model.py";
const SYNC_MANAGER: &str = "sofiadb-sync";
const PLATFORM_DIR: &str = "_platform";
const README: &str = "This folder is no longer read: with RBAC on the data model lives in the \
cube_app database (model_files). Export it with ./start-all.sh export-model.\n";

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ImportReport {
    pub imported: usize,
    /// Files placed in Platform with their whole relative path.
    pub unowned: Vec<String>,
    pub renamed_to: Option<PathBuf>,
}

fn names(model: &DataModel) -> BTreeSet<String> {
    model
        .cubes
        .keys()
        .chain(model.views.keys())
        .cloned()
        .collect()
}

/// The cube and view names in the folder that the database lacks. An error on
/// both sides, or on neither, counts as equal.
pub(crate) fn compare_cube_names(
    folder: &Result<DataModel, ModelError>,
    db: &Result<DataModel, ModelError>,
) -> Vec<String> {
    match (folder, db) {
        (Ok(f), Ok(d)) => {
            let have = names(d);
            names(f).into_iter().filter(|n| !have.contains(n)).collect()
        }
        // The folder compiled but the database does not: everything is missing.
        (Ok(f), Err(_)) => names(f).into_iter().collect(),
        _ => Vec::new(),
    }
}

/// Compiles both sides without an ownership policy and compares the cube
/// names. `Err("the imported model lacks cubes: a, b")` when some are missing.
pub fn verify_import(
    folder: &[(String, String)],
    db: &[(String, String)],
) -> Result<(), String> {
    let loader = ModelLoader::new();
    let f = loader.load_sources_with_policy(folder, None);
    let d = loader.load_sources_with_policy(db, None);
    let missing = compare_cube_names(&f, &d);
    if missing.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "the imported model lacks cubes: {}",
            missing.join(", ")
        ))
    }
}

fn rel_name(root: &Path, file: &Path) -> String {
    file.strip_prefix(root)
        .unwrap_or(file)
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect::<Vec<_>>()
        .join("/")
}

pub async fn import_if_empty(
    store: &Store,
    model_dir: &Path,
    today: &str,
) -> Result<ImportReport, String> {
    import_if_empty_with(store, model_dir, today, verify_import).await
}

/// [`import_if_empty`] with the cube-name check injected, so a test can force
/// a mismatch.
pub async fn import_if_empty_with<V>(
    store: &Store,
    model_dir: &Path,
    today: &str,
    verify: V,
) -> Result<ImportReport, String>
where
    V: Fn(&[(String, String)], &[(String, String)]) -> Result<(), String> + Send,
{
    let files = match cubemodel::model_files(model_dir) {
        Ok(f) => f,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Vec::new(),
        Err(e) => return Err(format!("Cannot read {}: {e}", model_dir.display())),
    };
    let empty = store.model_is_empty().await.map_err(|e| e.to_string())?;
    if !empty {
        if !files.is_empty() {
            tracing::warn!(
                "{} holds model files but the model is already in the RBAC database; \
                 the folder is ignored",
                model_dir.display()
            );
        }
        return Ok(ImportReport::default());
    }
    if files.is_empty() {
        return Ok(ImportReport::default());
    }

    let mut folder_sources: Vec<(String, String)> = Vec::new();
    for f in &files {
        let content = std::fs::read_to_string(f)
            .map_err(|e| format!("Cannot read {}: {e}", f.display()))?;
        folder_sources.push((rel_name(model_dir, f), content));
    }

    let mut orgs: HashMap<String, Option<Uuid>> = HashMap::new();
    let mut changes = Vec::new();
    let mut unowned = Vec::new();
    for (rel, content) in &folder_sources {
        let (first, rest) = match rel.split_once('/') {
            Some((a, b)) => (Some(a), b),
            None => (None, rel.as_str()),
        };
        let (org, path) = match first {
            Some(PLATFORM_DIR) => (None, rest.to_string()),
            Some(slug) => {
                if !orgs.contains_key(slug) {
                    let found = store
                        .organization_by_slug(slug)
                        .await
                        .map_err(|e| e.to_string())?
                        .map(|o| o.id);
                    orgs.insert(slug.to_string(), found);
                }
                match orgs[slug] {
                    Some(id) => (Some(id), rest.to_string()),
                    None => {
                        unowned.push(rel.clone());
                        (None, rel.clone())
                    }
                }
            }
            None => {
                unowned.push(rel.clone());
                (None, rel.clone())
            }
        };
        validate_path(&path).map_err(|e| format!("Cannot import {rel}: {e}"))?;
        changes.push(ModelChange::Put {
            id: None,
            organization_id: org,
            path,
            content: content.clone(),
            expected_version: None,
            managed_by: content
                .trim_start_matches('\u{feff}')
                .starts_with(SYNC_MARKER)
                .then(|| SYNC_MANAGER.to_string()),
        });
    }
    let imported = changes.len();

    let slugs: HashMap<Uuid, String> = orgs
        .iter()
        .filter_map(|(s, id)| id.map(|id| (id, s.clone())))
        .collect();
    let folder_for_check = folder_sources;
    // The check runs inside the transaction: a mismatch rolls everything back.
    let outcome = store
        .model_write("import", move |rows| {
            // A concurrent start may have imported already.
            if !rows.files.is_empty() {
                return Ok::<_, String>(Vec::new());
            }
            let mut planned: Vec<(String, String)> = changes
                .iter()
                .filter_map(|c| match c {
                    ModelChange::Put {
                        organization_id,
                        path,
                        content,
                        ..
                    } => match organization_id {
                        None => Some((format!("{PLATFORM_DIR}/{path}"), content.clone())),
                        Some(id) => slugs.get(id).map(|s| (format!("{s}/{path}"), content.clone())),
                    },
                    _ => None,
                })
                .collect();
            planned.sort_by(|a, b| a.0.cmp(&b.0));
            verify(&folder_for_check, &planned)?;
            Ok(changes)
        })
        .await
        .map_err(|e| e.to_string())??;
    if !outcome.changed {
        return Ok(ImportReport::default());
    }

    let renamed = PathBuf::from(format!("{}.imported-{today}", model_dir.display()));
    std::fs::rename(model_dir, &renamed)
        .map_err(|e| format!("Cannot rename {}: {e}", model_dir.display()))?;
    std::fs::create_dir_all(model_dir)
        .and_then(|_| std::fs::write(model_dir.join("README"), README))
        .map_err(|e| format!("Cannot write {}/README: {e}", model_dir.display()))?;

    Ok(ImportReport {
        imported,
        unowned,
        renamed_to: Some(renamed),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn load(files: &[(&str, &str)]) -> Result<DataModel, ModelError> {
        let s: Vec<_> = files
            .iter()
            .map(|(a, b)| (a.to_string(), b.to_string()))
            .collect();
        ModelLoader::new().load_sources_with_policy(&s, None)
    }

    const A: &str = "cubes:\n  - name: a\n    sql_table: t\n    dimensions:\n      - name: id\n        sql: id\n        type: number\n        primary_key: true\n";
    const B: &str = "cubes:\n  - name: b\n    sql_table: t\n    dimensions:\n      - name: id\n        sql: id\n        type: number\n        primary_key: true\n";

    #[test]
    fn compare_cube_names_reports_missing() {
        let both = load(&[("x/a.yml", A), ("x/b.yml", B)]);
        let only_a = load(&[("x/a.yml", A)]);
        assert!(both.is_ok() && only_a.is_ok());
        assert_eq!(compare_cube_names(&both, &only_a), vec!["b".to_string()]);
        assert!(compare_cube_names(&both, &both).is_empty());
        let bad1 = load(&[("x/a.yml", "cubes: [")]);
        let bad2 = load(&[("x/b.yml", "cubes: [")]);
        assert!(bad1.is_err() && bad2.is_err());
        assert!(compare_cube_names(&bad1, &bad2).is_empty());
    }
}
