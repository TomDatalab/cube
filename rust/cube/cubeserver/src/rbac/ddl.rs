//! The SQL of a model, as Redgate's "Generate SQL": tables with their keys,
//! indexes, checks and comments, then the foreign keys of its references.
//! Pure; [`create_statements`] is what "Create in database" runs, only for
//! the tables the model designs (drafts).

use std::collections::HashSet;

use cubedriver::DatabaseStructure;

use crate::handlers::scaffold::quote;

use super::cube_model::{
    validate, validate_draft_for_ddl, DraftColumn, DraftTable, Definition, ModelJoin, ModelTable, ModelView,
};

/// What [`script`] writes.
#[derive(Clone, Debug, Default)]
pub struct ScriptOptions {
    /// DROP statements before the creates.
    pub drop: bool,
    /// Only the tables the model designs.
    pub only_new: bool,
    /// Only these aliases.
    pub only: Option<Vec<String>>,
    /// COMMENT statements (or clauses) for comments.
    pub comments: bool,
}

/// A statement to run. The statements of one draft (its scripts, CREATE
/// TABLE, indexes and comments) come together and carry its `schema.table`;
/// the CREATE TABLE `creates` it, so a run knows which tables now exist.
#[derive(Clone, Debug, PartialEq)]
pub struct Statement {
    pub table: Option<String>,
    pub sql: String,
    pub creates: bool,
}

fn supported(db_type: &str) -> Result<bool, String> {
    match db_type {
        "postgres" => Ok(false),
        "mysql" => Ok(true),
        other => Err(format!("Criar tabelas não é suportado para {other}")),
    }
}

/// `'text'` with its quotes doubled.
fn literal(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

fn qualified(db_type: &str, table: &ModelTable) -> String {
    qualified_name(db_type, &table.schema, &table.table)
}

fn qualified_name(db_type: &str, schema: &str, name: &str) -> String {
    format!("{}.{}", quote(db_type, schema), quote(db_type, name))
}

/// The views in dependency order (what a view reads comes first), keeping
/// the definition order among independent ones. Dependencies outside
/// `views` are ignored. A cycle is an error naming the views left.
fn view_order<'a>(views: &[&'a ModelView]) -> Result<Vec<&'a ModelView>, String> {
    let ids: HashSet<&str> = views.iter().map(|v| v.id.as_str()).collect();
    let mut done: HashSet<&str> = HashSet::new();
    let mut left: Vec<&ModelView> = views.to_vec();
    let mut out = Vec::with_capacity(views.len());
    while !left.is_empty() {
        let ready = left.iter().position(|v| {
            v.depends_on_views
                .iter()
                .all(|d| !ids.contains(d.as_str()) || done.contains(d.as_str()))
        });
        match ready {
            Some(i) => {
                let v = left.remove(i);
                done.insert(v.id.as_str());
                out.push(v);
            }
            None => {
                let mut names: Vec<&str> = left.iter().map(|v| v.name.as_str()).collect();
                names.sort();
                return Err(format!(
                    "As views {} dependem umas das outras",
                    names.join(", ")
                ));
            }
        }
    }
    Ok(out)
}

/// `CREATE VIEW` of a view; its query is written as typed, trimmed.
fn view_create(db_type: &str, view: &ModelView) -> String {
    format!(
        "CREATE VIEW {} AS {}",
        qualified_name(db_type, &view.schema, &view.name),
        view.sql.trim()
    )
}

/// A portable type as the dialect writes it; a dialect type as it is.
fn column_type(kind: &str, mysql: bool) -> &str {
    match (kind, mysql) {
        ("integer", true) => "int",
        ("numeric", true) => "decimal(18,4)",
        ("numeric", false) => "numeric(18,4)",
        ("timestamp", true) => "datetime",
        (other, _) => other,
    }
}

fn column_sql(db_type: &str, c: &DraftColumn, comments: bool) -> String {
    let mysql = db_type == "mysql";
    let mut sql = format!(
        "{} {}",
        quote(db_type, &c.name),
        column_type(&c.kind, mysql)
    );
    if mysql && c.unsigned {
        sql.push_str(" UNSIGNED");
    }
    if mysql && c.zerofill {
        sql.push_str(" ZEROFILL");
    }
    if c.auto_increment {
        sql.push_str(if mysql {
            " AUTO_INCREMENT"
        } else {
            " GENERATED BY DEFAULT AS IDENTITY"
        });
    }
    if !c.nullable || c.primary_key {
        sql.push_str(" NOT NULL");
    }
    if let Some(default) = c.default.as_deref().filter(|d| !d.trim().is_empty()) {
        sql.push_str(&format!(" DEFAULT {default}"));
    }
    if let Some(check) = c.check.as_deref().filter(|d| !d.trim().is_empty()) {
        sql.push_str(&format!(" CHECK ({check})"));
    }
    if mysql && comments {
        if let Some(comment) = c.comment.as_deref().filter(|d| !d.is_empty()) {
            sql.push_str(&format!(" COMMENT {}", literal(comment)));
        }
    }
    sql
}

fn columns_list(db_type: &str, names: impl IntoIterator<Item = impl AsRef<str>>) -> String {
    names
        .into_iter()
        .map(|n| quote(db_type, n.as_ref()))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The CREATE TABLE of a draft, its keys and checks inside.
fn draft_create(db_type: &str, table: &ModelTable, draft: &DraftTable, comments: bool) -> String {
    let mysql = db_type == "mysql";
    let mut parts: Vec<String> = draft
        .columns
        .iter()
        .map(|c| column_sql(db_type, c, comments))
        .collect();
    let keys: Vec<&str> = draft
        .columns
        .iter()
        .filter(|c| c.primary_key)
        .map(|c| c.name.as_str())
        .collect();
    if !keys.is_empty() {
        let name = draft.primary_key_name.as_deref().filter(|n| !n.is_empty());
        parts.push(match name {
            Some(n) => format!(
                "CONSTRAINT {} PRIMARY KEY ({})",
                quote(db_type, n),
                columns_list(db_type, &keys)
            ),
            None => format!("PRIMARY KEY ({})", columns_list(db_type, &keys)),
        });
    }
    for key in &draft.unique_keys {
        parts.push(format!(
            "CONSTRAINT {} UNIQUE ({})",
            quote(db_type, &key.name),
            columns_list(db_type, &key.columns)
        ));
    }
    for check in &draft.checks {
        parts.push(format!(
            "CONSTRAINT {} CHECK ({})",
            quote(db_type, &check.name),
            check.expression
        ));
    }
    let mut sql = format!(
        "CREATE TABLE {} ({})",
        qualified(db_type, table),
        parts.join(", ")
    );
    if mysql && comments {
        if let Some(comment) = table.comment.as_deref().filter(|c| !c.is_empty()) {
            sql.push_str(&format!(" COMMENT={}", literal(comment)));
        }
    }
    sql
}

/// The CREATE TABLE of a table the connection has, from its columns.
fn existing_create(
    db_type: &str,
    table: &ModelTable,
    columns: &[cubedriver::SchemaColumn],
    key: Option<&str>,
) -> String {
    let mut parts: Vec<String> = columns
        .iter()
        .map(|c| format!("{} {}", quote(db_type, &c.name), c.type_))
        .collect();
    if let Some(key) = key {
        parts.push(format!("PRIMARY KEY ({})", quote(db_type, key)));
    }
    format!(
        "CREATE TABLE {} ({})",
        qualified(db_type, table),
        parts.join(", ")
    )
}

fn index_statements(db_type: &str, table: &ModelTable, draft: &DraftTable) -> Vec<String> {
    draft
        .indexes
        .iter()
        .map(|index| {
            let columns: Vec<String> = index
                .columns
                .iter()
                .map(|c| {
                    let q = quote(db_type, &c.name);
                    if c.desc {
                        format!("{q} DESC")
                    } else {
                        q
                    }
                })
                .collect();
            format!(
                "CREATE {}INDEX {} ON {} ({})",
                if index.unique { "UNIQUE " } else { "" },
                quote(db_type, &index.name),
                qualified(db_type, table),
                columns.join(", ")
            )
        })
        .collect()
}

/// The parent (the "one" side) and child aliases of a reference, with the
/// column pairs as (child, parent).
fn reference_ends(j: &ModelJoin) -> (&str, &str, Vec<(&str, &str)>) {
    let parent_is_from = j.relationship == "one_to_many";
    let mut pairs = vec![if parent_is_from {
        (j.to.column.as_str(), j.from.column.as_str())
    } else {
        (j.from.column.as_str(), j.to.column.as_str())
    }];
    for p in &j.pairs {
        pairs.push(if parent_is_from {
            (p.to.as_str(), p.from.as_str())
        } else {
            (p.from.as_str(), p.to.as_str())
        });
    }
    if parent_is_from {
        (j.from.alias.as_str(), j.to.alias.as_str(), pairs)
    } else {
        (j.to.alias.as_str(), j.from.alias.as_str(), pairs)
    }
}

fn fk_name(j: &ModelJoin, child: &str, parent: &str) -> String {
    j.name
        .clone()
        .filter(|n| !n.is_empty())
        .unwrap_or_else(|| format!("fk_{child}_{parent}"))
}

fn fk_statement(db_type: &str, def: &Definition, j: &ModelJoin) -> Option<(String, String)> {
    let (parent, child, pairs) = reference_ends(j);
    let find = |alias: &str| def.tables.iter().find(|t| t.alias == alias);
    let (parent_table, child_table) = (find(parent)?, find(child)?);
    let name = fk_name(j, child, parent);
    let mut sql = format!(
        "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
        qualified(db_type, child_table),
        quote(db_type, &name),
        columns_list(db_type, pairs.iter().map(|(c, _)| *c)),
        qualified(db_type, parent_table),
        columns_list(db_type, pairs.iter().map(|(_, p)| *p)),
    );
    for (clause, action) in [("ON UPDATE", &j.on_update), ("ON DELETE", &j.on_delete)] {
        if let Some(a) = action.as_deref().filter(|a| *a != "none") {
            sql.push_str(&format!(" {clause} {}", a.to_ascii_uppercase()));
        }
    }
    Some((child.to_string(), sql))
}

fn drop_fk(db_type: &str, def: &Definition, j: &ModelJoin) -> Option<String> {
    let (parent, child, _) = reference_ends(j);
    let child_table = def.tables.iter().find(|t| t.alias == child)?;
    let name = fk_name(j, child, parent);
    Some(format!(
        "ALTER TABLE {} DROP {} {}",
        qualified(db_type, child_table),
        if db_type == "mysql" {
            "FOREIGN KEY"
        } else {
            "CONSTRAINT"
        },
        quote(db_type, &name)
    ))
}

/// Postgres' COMMENT statements for a table and its columns.
fn comment_statements(db_type: &str, table: &ModelTable) -> Vec<String> {
    if db_type == "mysql" {
        return Vec::new();
    }
    let mut out = Vec::new();
    let name = qualified(db_type, table);
    if let Some(c) = table.comment.as_deref().filter(|c| !c.is_empty()) {
        out.push(format!("COMMENT ON TABLE {name} IS {}", literal(c)));
    }
    if let Some(draft) = &table.draft {
        for column in &draft.columns {
            if let Some(c) = column.comment.as_deref().filter(|c| !c.is_empty()) {
                out.push(format!(
                    "COMMENT ON COLUMN {name}.{} IS {}",
                    quote(db_type, &column.name),
                    literal(c)
                ));
            }
        }
    }
    out
}

fn mysql_text_key(table: &ModelTable, draft: &DraftTable) -> Result<(), String> {
    if let Some(c) = draft
        .columns
        .iter()
        .find(|c| c.primary_key && c.kind == "text")
    {
        return Err(format!(
            "No MySQL a chave primária {}.{}.{} não pode ser text: use integer, bigint ou outro tipo",
            table.schema, table.table, c.name
        ));
    }
    Ok(())
}

fn comments_on(def: &Definition) -> bool {
    def.settings
        .as_ref()
        .and_then(|s| s.sql_generation.as_ref())
        .and_then(|g| g.comments)
        .unwrap_or(true)
}

/// What "Create in database" runs: each draft's own scripts around its
/// CREATE TABLE, then the indexes, the foreign keys whose child is a draft,
/// and the comments.
pub fn create_statements(def: &Definition, db_type: &str) -> Result<Vec<Statement>, String> {
    let mysql = supported(db_type)?;
    let comments = comments_on(def);
    let mut out = Vec::new();
    for table in &def.tables {
        let Some(draft) = &table.draft else { continue };
        validate_draft_for_ddl(table, draft)?;
        if mysql {
            mysql_text_key(table, draft)?;
        }
        let mut group: Vec<String> = Vec::new();
        if let Some(s) = draft.script_before.as_deref().filter(|s| !s.trim().is_empty()) {
            group.push(s.to_string());
        }
        let create_at = group.len();
        group.push(draft_create(db_type, table, draft, comments));
        if let Some(s) = draft.script_after.as_deref().filter(|s| !s.trim().is_empty()) {
            group.push(s.to_string());
        }
        group.extend(index_statements(db_type, table, draft));
        if comments {
            group.extend(comment_statements(db_type, table));
        }
        let name = format!("{}.{}", table.schema, table.table);
        out.extend(group.into_iter().enumerate().map(|(i, sql)| Statement {
            table: Some(name.clone()),
            sql,
            creates: i == create_at,
        }));
    }
    let drafts: HashSet<&str> = def
        .tables
        .iter()
        .filter(|t| t.draft.is_some())
        .map(|t| t.alias.as_str())
        .collect();
    for j in &def.joins {
        if let Some((child, sql)) = fk_statement(db_type, def, j) {
            if drafts.contains(child.as_str()) {
                out.push(Statement {
                    table: None,
                    sql,
                    creates: false,
                });
            }
        }
    }
    Ok(out)
}

fn optional(text: Option<&String>) -> Option<&str> {
    text.map(|s| s.as_str()).filter(|s| !s.trim().is_empty())
}

/// The whole script of the model, as Redgate's "Generate SQL": the drop
/// part first when asked, then the creates, each statement ending in `;`.
pub fn script(
    def: &Definition,
    columns: &DatabaseStructure,
    db_type: &str,
    opts: &ScriptOptions,
) -> Result<String, String> {
    let mysql = supported(db_type)?;
    validate(def)?;
    let included: Vec<&ModelTable> = def
        .tables
        .iter()
        .filter(|t| !opts.only_new || t.draft.is_some())
        .filter(|t| opts.only.as_ref().is_none_or(|only| only.contains(&t.alias)))
        .collect();
    let aliases: HashSet<&str> = included.iter().map(|t| t.alias.as_str()).collect();
    let joins: Vec<&ModelJoin> = def
        .joins
        .iter()
        .filter(|j| {
            let (parent, child, _) = reference_ends(j);
            aliases.contains(parent) && aliases.contains(child)
        })
        .collect();
    let views: Vec<&ModelView> = def
        .views
        .iter()
        .filter(|v| opts.only.as_ref().is_none_or(|only| only.contains(&format!("view:{}", v.id))))
        .collect();
    let views = view_order(&views)?;
    let scripts = def.settings.as_ref().and_then(|s| s.scripts.as_ref());
    let mut out: Vec<String> = Vec::new();
    let mut push = |sql: &str| out.push(format!("{};\n", sql.trim_end().trim_end_matches(';')));

    if opts.drop {
        if let Some(s) = optional(scripts.and_then(|s| s.drop_before.as_ref())) {
            push(s);
        }
        for v in views.iter().rev() {
            push(&format!(
                "DROP VIEW IF EXISTS {}",
                qualified_name(db_type, &v.schema, &v.name)
            ));
        }
        for j in &joins {
            if let Some(sql) = drop_fk(db_type, def, j) {
                push(&sql);
            }
        }
        for table in included.iter().rev() {
            push(&format!("DROP TABLE IF EXISTS {}", qualified(db_type, table)));
        }
        if let Some(s) = optional(scripts.and_then(|s| s.drop_after.as_ref())) {
            push(s);
        }
    }
    if let Some(s) = optional(scripts.and_then(|s| s.create_before.as_ref())) {
        push(s);
    }
    let mut after: Vec<String> = Vec::new();
    for table in &included {
        match &table.draft {
            Some(draft) => {
                validate_draft_for_ddl(table, draft)?;
                if mysql {
                    mysql_text_key(table, draft)?;
                }
                if let Some(s) = optional(draft.script_before.as_ref()) {
                    push(s);
                }
                push(&draft_create(db_type, table, draft, opts.comments));
                if let Some(s) = optional(draft.script_after.as_ref()) {
                    push(s);
                }
                after.extend(index_statements(db_type, table, draft));
            }
            None => {
                let cols = columns
                    .get(&table.schema)
                    .and_then(|t| t.get(&table.table))
                    .map(Vec::as_slice)
                    .unwrap_or(&[]);
                let key = (def.primary.as_deref() == Some(table.alias.as_str()))
                    .then_some(def.primary_key.as_deref())
                    .flatten();
                push(&existing_create(db_type, table, cols, key));
            }
        }
        if opts.comments {
            after.extend(comment_statements(db_type, table));
        }
    }
    for sql in &after {
        push(sql);
    }
    for j in &joins {
        if let Some((_, sql)) = fk_statement(db_type, def, j) {
            push(&sql);
        }
    }
    for v in &views {
        if let Some(s) = optional(v.script_before.as_ref()) {
            push(s);
        }
        push(&view_create(db_type, v));
        if let Some(s) = optional(v.script_after.as_ref()) {
            push(s);
        }
        if opts.comments && !mysql {
            if let Some(c) = v.comment.as_deref().filter(|c| !c.is_empty()) {
                push(&format!(
                    "COMMENT ON VIEW {} IS {}",
                    qualified_name(db_type, &v.schema, &v.name),
                    literal(c)
                ));
            }
        }
    }
    if let Some(s) = optional(scripts.and_then(|s| s.create_after.as_ref())) {
        push(s);
    }
    Ok(out.concat())
}

