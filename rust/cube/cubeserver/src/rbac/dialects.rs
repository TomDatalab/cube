/// The dialect of a connection type, if the model designs tables for it.
pub fn of(db_type: &str) -> Option<&'static Dialect> {
    DIALECTS.iter().find(|d| d.db_types.contains(&db_type))
}

/// A dialect by its id.
pub fn by_id(id: &str) -> Option<&'static Dialect> {
    DIALECTS.iter().find(|d| d.id == id)
}

impl Dialect {
    /// Quotes an identifier as this dialect's DDL does.
    pub fn quote(&self, db_type: &str, ident: &str) -> String {
        if self.backticks {
            return format!("`{}`", ident.replace('`', "``"));
        }
        crate::handlers::scaffold::quote(db_type, ident)
    }

    /// A portable type as this dialect writes it; any other type as it is,
    /// its base name spelled as the dialect lists it.
    pub fn column_type(&self, kind: &str) -> String {
        let t = kind.trim();
        if let Some(i) = super::cube_model::TYPES.iter().position(|p| p.eq_ignore_ascii_case(t)) {
            return self.portable[i].to_string();
        }
        let (base, rest) = match t.find('(') {
            Some(at) => (t[..at].trim(), &t[at..]),
            None => (t, ""),
        };
        match self.types.iter().find(|(n, _)| n.eq_ignore_ascii_case(base)) {
            Some((name, _)) => format!("{name}{rest}"),
            None => t.to_string(),
        }
    }

    /// A type of the dialect's list, its parameters checked; the 7 portable
    /// types are valid everywhere.
    pub fn valid_type(&self, ty: &str) -> bool {
        let t = ty.trim();
        if super::cube_model::TYPES.iter().any(|p| p.eq_ignore_ascii_case(t)) {
            return true;
        }
        self.valid_native(t, 0)
    }

    fn valid_native(&self, t: &str, depth: usize) -> bool {
        if depth > 4 {
            return false;
        }
        let (base, params) = match t.find('(') {
            Some(at) => {
                let Some(inner) = t[at + 1..].strip_suffix(')') else {
                    return false;
                };
                (t[..at].trim(), Some(inner))
            }
            None => (t, None),
        };
        let Some((_, param)) = self.types.iter().find(|(n, _)| n.eq_ignore_ascii_case(base)) else {
            return false;
        };
        let numbers = |p: &str| -> Option<Vec<u32>> {
            p.split(',').map(|n| n.trim().parse::<u32>().ok()).collect()
        };
        match (param, params) {
            (Param::None, None) => true,
            (Param::Size { required }, None) => !required,
            (Param::Precision | Param::Free, None) => true,
            (Param::Type, None) => false,
            (Param::None, Some(_)) => false,
            (Param::Size { .. }, Some(p)) => {
                // SQL Server's `max` is a size too.
                p.trim().eq_ignore_ascii_case("max")
                    || numbers(p).is_some_and(|n| n.len() == 1 && n[0] >= 1)
            }
            (Param::Precision, Some(p)) => numbers(p).is_some_and(|n| match n.as_slice() {
                [p] => *p >= 1,
                [p, s] => *p >= 1 && s <= p,
                _ => false,
            }),
            (Param::Type, Some(inner)) => self.valid_native(inner.trim(), depth + 1),
            (Param::Free, Some(p)) => !p.trim().is_empty(),
        }
    }

    /// What the editor needs: the type list, the portable types as written
    /// here, and what a column and a table can have.
    pub fn to_json(&self) -> Value {
        let param = |p: &Param| match p {
            Param::None => "none",
            Param::Size { required: false } => "size",
            Param::Size { required: true } => "size!",
            Param::Precision => "precision",
            Param::Type => "type",
            Param::Free => "free",
        };
        json!({
            "id": self.id,
            "label": self.label,
            "types": self.types.iter().map(|(n, p)| json!([n, param(p)])).collect::<Vec<_>>(),
            "portable": {
                "text": self.portable[0], "integer": self.portable[1], "bigint": self.portable[2],
                "numeric": self.portable[3], "boolean": self.portable[4], "date": self.portable[5],
                "timestamp": self.portable[6],
            },
            "text": self.text,
            "canCreate": self.no_create.is_none(),
            "canSql": self.no_sql.is_none(),
            "reason": self.no_create.or(self.no_sql),
            "features": {
                "primaryKey": self.key != Key::None,
                "unique": self.unique,
                "check": self.check,
                "foreignKey": self.fk != Fk::None,
                "index": self.index != Index::None,
                "comments": self.comments != Comments::None,
                "autoIncrement": self.auto != Auto::None,
                "unsigned": self.unsigned,
                "notNull": self.not_null || self.nullable_wrap,
                "default": self.default,
                "views": self.views,
            },
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_connector_has_a_dialect() {
        for db_type in [
            "postgres", "mysql", "clickhouse", "bigquery", "snowflake", "mssql", "redshift", "druid",
            "firebolt", "cubestore", "crate", "materialize", "questdb", "vertica", "mongobi",
            "prestodb", "trino", "pinot", "athena", "mysqlauroraserverless", "dremio", "ksql",
            "databricks-jdbc", "hive", "oracle", "sqlite", "duckdb",
        ] {
            assert!(of(db_type).is_some(), "{db_type}");
        }
        let ids: std::collections::HashSet<_> = DIALECTS.iter().map(|d| d.id).collect();
        assert_eq!(ids.len(), DIALECTS.len());
    }

    #[test]
    fn types_are_checked_and_spelled_as_listed() {
        let ch = of("clickhouse").unwrap();
        assert!(ch.valid_type("String"));
        assert!(ch.valid_type("string"));
        assert!(ch.valid_type("Nullable(String)"));
        assert!(ch.valid_type("LowCardinality(Nullable(String))"));
        assert!(ch.valid_type("DateTime64(3, 'UTC')"));
        assert!(ch.valid_type("Decimal(18,4)"));
        assert!(!ch.valid_type("Nullable(Nope)"));
        assert!(!ch.valid_type("FixedString"));
        assert_eq!(ch.column_type("string"), "String");
        assert_eq!(ch.column_type("nullable(String)"), "Nullable(String)");
        assert_eq!(ch.column_type("timestamp"), "DateTime64(3)");
        let ms = of("mssql").unwrap();
        assert!(ms.valid_type("nvarchar(max)"));
        assert!(ms.valid_type("varchar(50)"));
        let pg = of("postgres").unwrap();
        assert!(pg.valid_type("varchar(255)"));
        assert!(!pg.valid_type("varchar(0)"));
        assert!(!pg.valid_type("String"));
        assert!(pg.valid_type("TEXT"));
        assert_eq!(of("mysql").unwrap().column_type("integer"), "int");
        assert_eq!(of("oracle").unwrap().column_type("boolean"), "NUMBER(1)");
    }

    #[test]
    fn read_only_databases_say_why() {
        for db in ["druid", "pinot", "mongobi"] {
            let d = of(db).unwrap();
            assert!(d.no_create.is_some() && d.no_sql.is_some(), "{db}");
            assert_eq!(d.to_json()["canCreate"], false);
        }
        assert_eq!(of("athena").unwrap().to_json()["canSql"], true);
        assert_eq!(of("athena").unwrap().to_json()["canCreate"], false);
        assert_eq!(of("clickhouse").unwrap().to_json()["canCreate"], true);
    }
}
