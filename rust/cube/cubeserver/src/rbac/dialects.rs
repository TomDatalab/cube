//! What each connector's database accepts when the model designs tables:
//! its column types, how the 7 portable types are written in it, and the
//! parts of a CREATE TABLE it has (keys, checks, foreign keys, indexes,
//! comments, auto increment, views). [`super::ddl`] writes the SQL from it,
//! and the editor gets it from the connection (see [`Dialect::to_json`]).

use serde_json::{json, Value};

/// What a type takes in parentheses.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Param {
    /// Nothing: `text`.
    None,
    /// One size, `required` when it cannot go without: `varchar(255)`.
    Size { required: bool },
    /// A precision with an optional scale: `numeric(18,4)`.
    Precision,
    /// Another type of the dialect: `Nullable(String)`, `Array(Int64)`.
    Type,
    /// Anything: `Enum8('a' = 1)`, `DateTime64(3, 'UTC')`.
    Free,
}

/// How a primary key is declared.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Key {
    /// `[CONSTRAINT n] PRIMARY KEY (cols)` among the columns.
    Constraint,
    /// The same, followed by a clause: BigQuery's ` NOT ENFORCED`.
    Informational(&'static str),
    /// ClickHouse: the key is the table's `ORDER BY`.
    OrderBy,
    /// Firebolt: `PRIMARY INDEX cols` after the column list.
    PrimaryIndex,
    /// Cube Store: `UNIQUE KEY (cols)` after the column list.
    UniqueKey,
    /// ksqlDB: `PRIMARY KEY` on the key column itself.
    OnColumn,
    None,
}

/// How a foreign key is declared.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Fk {
    /// `ALTER TABLE … ADD CONSTRAINT … FOREIGN KEY …`, after the tables.
    Alter,
    /// The same with a trailing clause and no actions: BigQuery's
    /// ` NOT ENFORCED`, Hive's ` DISABLE NOVALIDATE`.
    AlterInformational(&'static str),
    /// Inside the child's CREATE TABLE (SQLite, DuckDB): no ALTER for it,
    /// so the parents are created first.
    Inline,
    None,
}

/// Which `ON DELETE` / `ON UPDATE` actions a foreign key takes.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Actions {
    All,
    /// SQL Server: no RESTRICT (NO ACTION is the same).
    NoRestrict,
    /// Oracle: ON DELETE CASCADE or SET NULL, no ON UPDATE.
    DeleteOnly,
    /// DuckDB: only NO ACTION / RESTRICT.
    RestrictOnly,
    None,
}

/// How an index is written.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Index {
    /// `CREATE [UNIQUE] INDEX n ON schema.table (cols)`.
    Create,
    /// SQLite: `CREATE INDEX schema.n ON table (cols)`.
    SchemaOnName,
    /// Materialize: no UNIQUE, no DESC.
    CreatePlain,
    /// ClickHouse: a data skipping index, `ALTER TABLE … ADD INDEX`.
    Skipping,
    /// Cube Store: `INDEX n (cols)` after the column list.
    Inline,
    None,
}

/// How comments are written.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Comments {
    /// `COMMENT ON TABLE|COLUMN|VIEW … IS '…'`.
    On,
    /// MySQL: `col … COMMENT '…'`, `… ) COMMENT='…'`.
    MySql,
    /// `col … COMMENT '…'`, `… ) COMMENT '…'` (ClickHouse after its engine,
    /// Databricks, Hive, Trino, Athena).
    Inline,
    /// BigQuery: `OPTIONS(description='…')`.
    Options,
    /// SQL Server: `EXEC sp_addextendedproperty 'MS_Description', …`.
    Extended,
    None,
}

/// How an auto-increment column is written.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Auto {
    /// ` GENERATED BY DEFAULT AS IDENTITY`.
    Identity,
    /// ` AUTO_INCREMENT`.
    AutoIncrement,
    /// ` IDENTITY(1,1)`.
    IdentityFn,
    /// Snowflake's ` AUTOINCREMENT`.
    Autoincrement,
    /// SQLite: ` PRIMARY KEY AUTOINCREMENT` on a single integer key.
    SqliteKey,
    /// DuckDB: a sequence and ` DEFAULT nextval('…')`.
    Sequence,
    None,
}

/// What goes after a CREATE TABLE's column list.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Suffix {
    None,
    /// ` ENGINE = MergeTree ORDER BY (…)`.
    ClickHouse,
    /// ` USING DELTA`.
    Delta,
    /// ` STORED AS ORC`.
    Orc,
    /// Athena's Iceberg table: a LOCATION to fill in.
    Iceberg,
    /// ksqlDB's Kafka topic.
    Kafka,
}

/// Dropping a table when the script starts with drops.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Drop {
    /// `DROP TABLE IF EXISTS`.
    IfExists,
    /// Oracle before 23c: a block that ignores a missing table.
    OracleBlock,
    /// `DROP TABLE` (no IF EXISTS).
    Plain,
}

/// One database's dialect.
#[derive(Clone, Copy, Debug)]
pub struct Dialect {
    /// The name the editor knows it by.
    pub id: &'static str,
    pub label: &'static str,
    /// The connection types (`cube.yml` `type:`) that speak it.
    pub db_types: &'static [&'static str],
    /// Its types; validated without case, written as spelled here.
    pub types: &'static [(&'static str, Param)],
    /// The 7 portable types as it writes them: text, integer, bigint,
    /// numeric, boolean, date, timestamp.
    pub portable: [&'static str; 7],
    /// The type of a new text column.
    pub text: &'static str,
    /// Why "Create in database" cannot run, when it cannot.
    pub no_create: Option<&'static str>,
    /// Why no SQL can be written at all, when it cannot.
    pub no_sql: Option<&'static str>,
    pub key: Key,
    pub unique: bool,
    pub check: bool,
    /// A column's own CHECK is written as a table constraint.
    pub column_check_as_constraint: bool,
    pub not_null: bool,
    pub default: bool,
    /// DEFAULT before NOT NULL (Oracle requires it).
    pub default_first: bool,
    /// A nullable column is `Nullable(type)` (ClickHouse).
    pub nullable_wrap: bool,
    pub fk: Fk,
    pub actions: Actions,
    pub index: Index,
    pub index_desc: bool,
    pub comments: Comments,
    pub auto: Auto,
    /// MySQL's UNSIGNED / ZEROFILL.
    pub unsigned: bool,
    /// Tables are `schema.table`; without, just `table`.
    pub schemas: bool,
    pub views: bool,
    pub suffix: Suffix,
    pub drop: Drop,
    /// Identifiers in backticks for its DDL (Athena's DDL is Hive's).
    pub backticks: bool,
}

